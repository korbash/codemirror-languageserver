#!/usr/bin/env node

/**
 * Generate typed LSP methods enum from vscode-languageserver-protocol constants
 *
 * This script extracts all LSP request methods from the protocol library
 * and generates a TypeScript enum with proper naming conventions.
 */

const lsp = require('vscode-languageserver-protocol');

// Get all Request namespaces
const requestNames = Object.keys(lsp).filter(
    (key) =>
        key.endsWith('Request') &&
        !key.startsWith('Request') &&
        !key.startsWith('Protocol'),
);

// Get all Notification namespaces
const notificationNames = Object.keys(lsp).filter(
    (key) =>
        key.endsWith('Notification') &&
        !key.startsWith('Notification') &&
        !key.startsWith('Protocol'),
);

// Extract methods with their original namespace names
const requestMethods = requestNames
    .map((name) => ({ name, method: lsp[name]?.method }))
    .filter((x) => x.method)
    .sort((a, b) => a.method.localeCompare(b.method));

const notificationMethods = notificationNames
    .map((name) => ({ name, method: lsp[name]?.method }))
    .filter((x) => x.method)
    .sort((a, b) => a.method.localeCompare(b.method));

// Convert method string to enum key
function methodToEnumKey(method) {
    return method
        .replace(/\//g, '_') // / -> _
        .replace(/\$/g, 'DOLLAR_') // $ -> DOLLAR_
        .replace(/-/g, '_') // - -> _
        .toUpperCase();
}

// Generate TypeScript enum
function generateEnum(title, methods, enumName) {
    console.log(`// === ${title} ===`);
    console.log(`export const ${enumName} = {`);

    // Group by category for better organization
    const categories = {};

    methods.forEach(({ method }) => {
        const category = method.split('/')[0] || 'general';
        if (!categories[category]) {
            categories[category] = [];
        }
        categories[category].push(method);
    });

    // Output categorized methods
    Object.keys(categories)
        .sort()
        .forEach((category) => {
            console.log(
                `    // ${category.charAt(0).toUpperCase() + category.slice(1)}`,
            );

            categories[category].forEach((method) => {
                const enumKey = methodToEnumKey(method);
                console.log(`    ${enumKey}: '${method}',`);
            });
            console.log('');
        });

    console.log('} as const;\n');

    // Generate union type
    const unionTypeName = enumName.replace('Methods', 'MethodValue');
    console.log(
        `export type ${unionTypeName} = (typeof ${enumName})[keyof typeof ${enumName}];\n`,
    );
}

console.log('// Auto-generated LSP method constants');
console.log('// Generated by scripts/generate-lsp-methods.js\n');

// Generate request methods
generateEnum('LSP Request Methods', requestMethods, 'LSPMethods');

// Generate notification methods
generateEnum(
    'LSP Notification Methods',
    notificationMethods,
    'LSPNotifications',
);

// Generate statistics
console.log('// === Statistics ===');
console.log(`// Total request methods: ${requestMethods.length}`);
console.log(`// Total notification methods: ${notificationMethods.length}`);
console.log(
    `// Total methods: ${requestMethods.length + notificationMethods.length}`,
);

// Generate usage examples
console.log('\n// === Usage Examples ===');
console.log('// import { LSPMethods, LSPNotifications } from "./types";');
console.log(
    '// await requestManager.sendRequest(LSPMethods.TEXT_DOCUMENT_COMPLETION, params);',
);
console.log(
    '// await connection.sendNotification(LSPNotifications.TEXT_DOCUMENT_DID_OPEN, params);',
);

console.log('\n// === Available Request Methods ===');
requestMethods.forEach(({ method }) => {
    console.log(`// ${methodToEnumKey(method)} = '${method}'`);
});
